# "Check again" already exists in the main catalog: drop it from this one
_i = KEYS.index("Check again (about 2 minutes)")
del KEYS[_i]
for _v in T.values():
    del _v[_i]

out = Path(__file__).resolve().parent.parent / "src" / "locales"
ids = [f"tune{i + 1:02d}" for i in range(len(KEYS))]
for lang, values in T.items():
    assert len(values) == len(KEYS), (lang, len(values), len(KEYS))
    for k, v in zip(KEYS, values):
        import re
        assert sorted(re.findall(r"\{\d+\}", k)) == sorted(re.findall(r"\{\d+\}", v)), (lang, k, v)
    (out / f"tune-{lang}.json").write_text(json.dumps(dict(zip(ids, values)), ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
(out / "tune-en.json").write_text(json.dumps(dict(zip(ids, KEYS)), ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print("wrote", len(KEYS), "strings x", len(T) + 1, "languages")
